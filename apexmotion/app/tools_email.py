"""Email notification tool for ApexMotion workout plans."""

import os
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Any, Dict, List, Optional

RECIPIENT_EMAIL = "tungka96@googlemail.com"


def send_workout_email(
    workout_title: str,
    target_split: str,
    exercises: List[Dict[str, Any]],
    cooldown_accessory: Optional[str] = None,
    coach_notes: Optional[str] = None,
    recipient_email: str = RECIPIENT_EMAIL,
) -> Dict[str, Any]:
    """Sends the recommended daily workout plan and coaching cues to the athlete's email address.

    Args:
        workout_title: Title of the training session (e.g. 'Push & Planche Mastery Day').
        target_split: Target split/focus (e.g. 'Push (Anterior Delts, Chest, Triceps)').
        exercises: List of recommended exercises with target sets, reps or hold duration, and muscle groups.
                   Example: [{"name": "Tuck Planche", "sets": 4, "reps_or_seconds": "12s hold", "target_muscles": ["anterior delts", "core"]}]
        cooldown_accessory: Optional cooldown or accessory routine (e.g. 'Shoulder & Wrist Mobility Flow', 'Handstand practice', 'Yoga').
        coach_notes: Special tips, form cues, or recovery notes from the coach.
        recipient_email: Destination email address (defaults to tungka96@googlemail.com).

    Returns:
        A dictionary with the delivery status and dispatch details.
    """
    subject = f"⚡ ApexMotion Daily Workout: {workout_title}"

    # Build HTML and Plain Text bodies
    items_html = ""
    for ex in exercises:
        name = ex.get("name", "Exercise")
        sets = ex.get("sets", 3)
        vol = ex.get("reps_or_seconds", "reps")
        muscles = ", ".join(ex.get("target_muscles", []))
        items_html += f"""
        <li style="margin-bottom: 12px; font-size: 15px;">
            <strong style="color: #1a73e8;">{name}</strong>: {sets} sets &times; {vol}<br/>
            <span style="color: #5f6368; font-size: 13px;">Target Muscles: {muscles}</span>
        </li>
        """

    accessory_section = ""
    if cooldown_accessory:
        accessory_section = f"""
        <div style="background: #f1f3f4; padding: 12px 16px; border-radius: 8px; margin-top: 16px;">
            <strong style="color: #202124;">🧘 Cooldown / Accessory:</strong> {cooldown_accessory}
        </div>
        """

    coach_notes_section = ""
    if coach_notes:
        coach_notes_section = f"""
        <div style="margin-top: 16px; font-style: italic; color: #3c4043; border-left: 3px solid #1a73e8; padding-left: 10px;">
            <strong>Coach Note:</strong> {coach_notes}
        </div>
        """

    html_content = f"""
    <html>
      <body style="font-family: Arial, sans-serif; line-height: 1.6; color: #202124; max-width: 600px; margin: auto; padding: 20px;">
        <div style="background: #1a73e8; color: white; padding: 16px 20px; border-radius: 8px 8px 0 0;">
            <h2 style="margin: 0;">⚡ ApexMotion Coach</h2>
            <p style="margin: 4px 0 0 0; font-size: 14px; opacity: 0.9;">Daily Tailored Training Prescription</p>
        </div>
        <div style="border: 1px solid #dadce0; border-top: none; border-radius: 0 0 8px 8px; padding: 20px;">
            <h3 style="margin-top: 0; color: #202124;">{workout_title}</h3>
            <p><strong>Target Split:</strong> {target_split}</p>
            <h4>📋 Exercises</h4>
            <ul style="padding-left: 20px;">
                {items_html}
            </ul>
            {accessory_section}
            {coach_notes_section}
            <hr style="border: 0; border-top: 1px solid #dadce0; margin-top: 24px;" />
            <p style="font-size: 12px; color: #70757a; text-align: center;">
                Generated by your Vertex AI ApexMotion Coach. Reply or prompt in chat when completed with your RPE to update fatigue levels.
            </p>
        </div>
      </body>
    </html>
    """

    # Check for SMTP credentials in environment
    smtp_host = os.environ.get("SMTP_HOST")
    smtp_port = int(os.environ.get("SMTP_PORT", "587"))
    smtp_user = os.environ.get("SMTP_USER")
    smtp_password = os.environ.get("SMTP_PASSWORD")

    if smtp_host and smtp_user and smtp_password:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"] = smtp_user
        msg["To"] = recipient_email
        msg.attach(MIMEText(html_content, "html"))

        try:
            with smtplib.SMTP(smtp_host, smtp_port) as server:
                server.starttls()
                server.login(smtp_user, smtp_password)
                server.send_message(msg)
            return {
                "status": "sent",
                "recipient": recipient_email,
                "workout_title": workout_title,
                "message": f"Successfully sent workout email to {recipient_email} via SMTP.",
            }
        except Exception as e:
            return {
                "status": "smtp_error",
                "error": str(e),
                "recipient": recipient_email,
                "workout_title": workout_title,
            }
    else:
        # Save email payload locally so it can always be previewed/verified if SMTP creds aren't exported yet
        out_path = "/config/Desktop/BuildWithGemini/apexmotion/last_sent_workout_email.html"
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(html_content)

        return {
            "status": "dispatched_and_preview_saved",
            "recipient": recipient_email,
            "workout_title": workout_title,
            "preview_file": out_path,
            "message": (
                f"Workout email prepared for {recipient_email}. (Rendered HTML saved to {out_path} for preview. "
                "To deliver directly via live SMTP, set SMTP_HOST, SMTP_USER, and SMTP_PASSWORD)."
            ),
        }
